-- V5. 외부 발행의 멱등키 유니크와 발행 상태 기록 (#263 PR1).
-- 지금까지는 Agent가 외부 시스템을 조회(GitHub 댓글 표식 등)해서만 중복을 막았다. 같은 논리적 발행은 DB에서도
-- unique(target, idempotency_key)로 한 줄만 만들 수 있게 하고, 외부에 쓰기 전에 RESERVED로 먼저 남긴다.
-- 티켓을 지우면(프로젝트 삭제) 발행 기록도 함께 지운다. 프로젝트 삭제가 JPQL 일괄 삭제라 DB 쪽 ON DELETE CASCADE로 처리한다.
-- 기존 티켓은 백필하지 않는다. 이미 끝난 발행은 티켓 상태가 막고, 이 테이블은 V5 이후의 발행 시도부터 쌓는다.

CREATE TABLE publications (
	publication_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	task_item_id uuid NOT NULL REFERENCES task_items (task_item_id) ON DELETE CASCADE,
	target varchar(10) NOT NULL,
	operation varchar(10) NOT NULL,
	idempotency_key varchar(200) NOT NULL,
	status varchar(20) NOT NULL,
	attempt_count integer NOT NULL,
	publish_batch_id uuid,
	external_id varchar(255),
	external_url varchar(2048),
	error_code varchar(50),
	created_at timestamptz(6) NOT NULL,
	reserved_at timestamptz(6) NOT NULL,
	sent_at timestamptz(6),
	updated_at timestamptz(6) NOT NULL,
	CONSTRAINT publications_target_idempotency_key_key UNIQUE (target, idempotency_key),
	CONSTRAINT publications_target_check CHECK (target IN ('GITHUB', 'SLACK', 'NOTION')),
	CONSTRAINT publications_operation_check CHECK (operation IN ('CREATE', 'LINK', 'UPDATE', 'COMMENT')),
	CONSTRAINT publications_status_check CHECK (status IN ('RESERVED', 'SENT', 'CONFIRMED', 'UNCERTAIN', 'FAILED'))
);
CREATE INDEX idx_publications_task_item_id ON publications (task_item_id);
CREATE INDEX idx_publications_publish_batch_id ON publications (publish_batch_id);
