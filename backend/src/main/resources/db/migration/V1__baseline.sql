-- V1 baseline: 엔티티(ddl-auto: create)가 PostgreSQL에 만들던 스키마와 같은 상태.
-- 이미 ddl-auto: update로 만들어진 DB는 baseline-on-migrate(baseline-version=1)로 이 파일을 건너뛴다.
-- 이 파일은 적용 후 수정하지 않는다. 변경은 새 V<n>__*.sql로 추가한다.

CREATE TABLE users (
	user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	login_id varchar(100) NOT NULL,
	password_hash varchar(255) NOT NULL,
	name varchar(100) NOT NULL,
	github_name varchar(100),
	slack_email varchar(254),
	slack_user_id varchar(30),
	slack_connection_status varchar(20),
	created_at timestamptz(6) NOT NULL,
	CONSTRAINT users_login_id_key UNIQUE (login_id),
	CONSTRAINT users_slack_connection_status_check
		CHECK (slack_connection_status IN ('CONNECTED', 'NOT_CONNECTED', 'ERROR'))
);

CREATE TABLE projects (
	project_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name varchar(100) NOT NULL,
	description varchar(500),
	github_owner varchar(100) NOT NULL,
	github_repo varchar(100) NOT NULL,
	notion_page_url varchar(500),
	notion_connection_status varchar(20),
	slack_channel_id varchar(30),
	github_connection varchar(20),
	slack_connection_status varchar(20),
	CONSTRAINT projects_github_owner_github_repo_key UNIQUE (github_owner, github_repo),
	CONSTRAINT projects_notion_connection_status_check
		CHECK (notion_connection_status IN ('CONNECTED', 'NOT_CONNECTED', 'ERROR')),
	CONSTRAINT projects_github_connection_check
		CHECK (github_connection IN ('CONNECTED', 'NOT_CONNECTED', 'ERROR')),
	CONSTRAINT projects_slack_connection_status_check
		CHECK (slack_connection_status IN ('CONNECTED', 'NOT_CONNECTED', 'ERROR'))
);

CREATE TABLE project_members (
	project_member_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	project_id bigint NOT NULL REFERENCES projects (project_id),
	user_id bigint REFERENCES users (user_id),
	name varchar(100) NOT NULL,
	github_name varchar(100),
	role varchar(10) NOT NULL DEFAULT 'MEMBER',
	repository_permission varchar(20),
	CONSTRAINT project_members_project_id_user_id_key UNIQUE (project_id, user_id),
	CONSTRAINT project_members_role_check CHECK (role IN ('ADMIN', 'MEMBER')),
	CONSTRAINT project_members_repository_permission_check
		CHECK (repository_permission IN ('GRANTED', 'DENIED', 'NO_ACCOUNT'))
);
CREATE INDEX idx_project_members_project_id ON project_members (project_id);

CREATE TABLE meetings (
	meeting_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	project_id bigint NOT NULL REFERENCES projects (project_id),
	created_by bigint NOT NULL REFERENCES users (user_id),
	title varchar(255) NOT NULL,
	meeting_date date NOT NULL,
	participants_json text NOT NULL,
	original_filename varchar(255) NOT NULL,
	original_content text NOT NULL
);
CREATE INDEX idx_meetings_project_id_meeting_date ON meetings (project_id, meeting_date);

CREATE TABLE analysis_tasks (
	analysis_task_id uuid PRIMARY KEY,
	meeting_id bigint NOT NULL REFERENCES meetings (meeting_id),
	status varchar(30) NOT NULL,
	stage varchar(100),
	input_json text NOT NULL,
	error_message text,
	progress_json text,
	created_at timestamptz(6) NOT NULL,
	finished_at timestamptz(6),
	CONSTRAINT analysis_tasks_status_check
		CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'PARTIALLY_FAILED', 'FAILED')),
	CONSTRAINT analysis_tasks_stage_check
		CHECK (stage IN ('EXTRACTING', 'NORMALIZING', 'REVIEWING', 'PUBLISHING', 'VERIFYING'))
);
CREATE INDEX idx_analysis_tasks_meeting_id ON analysis_tasks (meeting_id);

CREATE TABLE publish_batches (
	publish_batch_id uuid PRIMARY KEY,
	user_id bigint NOT NULL REFERENCES users (user_id),
	status varchar(30) NOT NULL,
	execution_mode varchar(10) NOT NULL,
	created_at timestamptz(6) NOT NULL,
	finished_at timestamptz(6),
	error_message text,
	entries_json text,
	CONSTRAINT publish_batches_status_check
		CHECK (status IN ('RUNNING', 'SUCCEEDED', 'PARTIAL_FAILED', 'FAILED'))
);
CREATE INDEX idx_publish_batches_user_id ON publish_batches (user_id);

CREATE TABLE task_items (
	task_item_id uuid PRIMARY KEY,
	task_id uuid NOT NULL REFERENCES analysis_tasks (analysis_task_id),
	work_key varchar(100),
	title varchar(255) NOT NULL,
	content_json text NOT NULL,
	action varchar(30) NOT NULL,
	reason text,
	review_status varchar(30) NOT NULL,
	publish_status varchar(30) NOT NULL,
	github_issue_number integer,
	github_issue_url varchar(2048),
	error_message text,
	assignee_member_id bigint REFERENCES project_members (project_member_id),
	ticket_status varchar(30) NOT NULL DEFAULT 'ASSIGNEE_REQUIRED',
	processing_type varchar(10) NOT NULL DEFAULT 'CREATE',
	publish_batch_id uuid REFERENCES publish_batches (publish_batch_id),
	publish_error_code varchar(50),
	publish_retryable boolean NOT NULL DEFAULT false,
	publish_outcome_unknown boolean NOT NULL DEFAULT false,
	previous_outcome_unknown boolean NOT NULL DEFAULT false,
	publish_target varchar(10) NOT NULL DEFAULT 'GITHUB',
	CONSTRAINT task_items_ticket_status_check CHECK (ticket_status IN (
		'ASSIGNEE_REQUIRED', 'PENDING_REVIEW', 'CONFIRMED', 'PUBLISHING', 'REJECTED',
		'PUBLISHED', 'LINKED', 'UPDATED', 'FAILED')),
	CONSTRAINT task_items_processing_type_check
		CHECK (processing_type IN ('CREATE', 'LINK', 'UPDATE')),
	CONSTRAINT task_items_publish_target_check
		CHECK (publish_target IN ('GITHUB', 'SLACK', 'NOTION'))
);
CREATE INDEX idx_task_items_task_id ON task_items (task_id);
CREATE INDEX idx_task_items_work_key ON task_items (work_key);

-- task_id의 FK는 V2에서 추가한다. (기존 DB의 고아 행 때문에 NOT VALID 후 VALIDATE 순서가 필요)
CREATE TABLE analysis_dispatches (
	task_id uuid PRIMARY KEY,
	state varchar(20) NOT NULL,
	published boolean NOT NULL,
	attempts integer NOT NULL,
	execution_mode varchar(10) NOT NULL,
	updated_at timestamptz(6),
	CONSTRAINT analysis_dispatches_state_check
		CHECK (state IN ('QUEUED', 'SUBMITTING', 'ACCEPTED', 'UNCERTAIN', 'EXHAUSTED'))
);

CREATE TABLE project_reindexes (
	project_reindex_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	project_id bigint NOT NULL REFERENCES projects (project_id),
	status varchar(20) NOT NULL,
	agent_job_id varchar(64),
	requested_at timestamptz(6) NOT NULL,
	finished_at timestamptz(6),
	error_message varchar(1000),
	progress_message varchar(500),
	indexed integer,
	skipped integer,
	total integer,
	index_count integer,
	last_synced_at timestamptz(6),
	CONSTRAINT project_reindexes_project_id_key UNIQUE (project_id),
	CONSTRAINT project_reindexes_status_check
		CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED'))
);
