-- V4. 에이전트 원본/사용자 수정본/발행본 리비전과 티켓 상태 이력 (#264).
-- task_items.content_json은 수정하면 덮어써지므로 원본이 남지 않는다. 시점별 전체 스냅샷을 따로 쌓는다.
-- 티켓을 지우면(프로젝트 삭제) 이력도 함께 지운다. 프로젝트 삭제가 JPQL 일괄 삭제라 DB 쪽 ON DELETE CASCADE로 처리한다.

CREATE TABLE task_item_revisions (
	task_item_revision_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	task_item_id uuid NOT NULL REFERENCES task_items (task_item_id) ON DELETE CASCADE,
	rev integer NOT NULL,
	kind varchar(20) NOT NULL,
	snapshot jsonb NOT NULL,
	schema_version integer NOT NULL,
	prompt_version varchar(64),
	model varchar(100),
	actor_user_id bigint,
	created_at timestamptz(6) NOT NULL,
	CONSTRAINT task_item_revisions_task_item_id_rev_key UNIQUE (task_item_id, rev),
	CONSTRAINT task_item_revisions_kind_check CHECK (kind IN ('AGENT', 'USER_EDIT', 'PUBLISHED'))
);

CREATE TABLE ticket_status_history (
	ticket_status_history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	task_item_id uuid NOT NULL REFERENCES task_items (task_item_id) ON DELETE CASCADE,
	from_status varchar(30),
	to_status varchar(30) NOT NULL,
	actor_user_id bigint,
	reason varchar(100),
	created_at timestamptz(6) NOT NULL,
	CONSTRAINT ticket_status_history_from_status_check CHECK (from_status IN (
		'ASSIGNEE_REQUIRED', 'PENDING_REVIEW', 'CONFIRMED', 'PUBLISHING', 'REJECTED',
		'PUBLISHED', 'LINKED', 'UPDATED', 'SKIPPED', 'FAILED')),
	CONSTRAINT ticket_status_history_to_status_check CHECK (to_status IN (
		'ASSIGNEE_REQUIRED', 'PENDING_REVIEW', 'CONFIRMED', 'PUBLISHING', 'REJECTED',
		'PUBLISHED', 'LINKED', 'UPDATED', 'SKIPPED', 'FAILED'))
);
CREATE INDEX idx_ticket_status_history_task_item_id_created_at ON ticket_status_history (task_item_id, created_at);

-- 기존 티켓마다 AGENT 리비전 1건(rev=1)을 만든다.
-- 지금까지는 수정이 content_json과 title을 덮어썼으므로, 이미 수정된 티켓의 이 리비전은 에이전트 원본이 아니라 V4 시점의 현재 값이다.
-- 만든 시각은 분석이 끝난 시각(없으면 시작 시각)으로 둔다. prompt_version, model은 알 수 없어 비워 둔다.
-- 먼저 content_json이 모두 JSON으로 읽히는지 검사하고, 아니면 아무것도 바꾸지 않고 해당 티켓 ID로 중단한다. (V2와 같은 방식)
DO $$
DECLARE
	r record;
	bad text := '';
BEGIN
	FOR r IN SELECT task_item_id, content_json FROM task_items LOOP
		BEGIN
			PERFORM r.content_json::jsonb;
		EXCEPTION WHEN OTHERS THEN
			bad := bad || E'\n  ' || r.task_item_id::text;
		END;
	END LOOP;
	IF bad <> '' THEN
		RAISE EXCEPTION 'V4 중단: content_json이 JSON이 아닌 티켓이 있어 리비전을 만들 수 없습니다. 데이터는 바꾸지 않았습니다.%', bad
			USING HINT = '해당 티켓의 content_json을 고치거나 정리한 뒤 다시 기동하세요.';
	END IF;
END
$$;

INSERT INTO task_item_revisions (task_item_id, rev, kind, snapshot, schema_version, created_at)
SELECT i.task_item_id, 1, 'AGENT',
	jsonb_build_object(
		'title', i.title,
		'assignee_member_id', i.assignee_member_id,
		'assignee_name', m.name,
		'publish_target', i.publish_target,
		'processing_type', i.processing_type,
		'content', i.content_json::jsonb),
	1,
	COALESCE(t.finished_at, t.created_at)
FROM task_items i
JOIN analysis_tasks t ON t.analysis_task_id = i.task_id
LEFT JOIN project_members m ON m.project_member_id = i.assignee_member_id;

